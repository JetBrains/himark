# Builds the Rust staticlib for the device and the simulator, writes
# the xcconfig that links it, and (re)generates the Xcode project.

set -euo pipefail
cd "$(dirname "$0")"
ROOT="$(cd ../.. && pwd)"

# The simulator slice runs on the host's architecture.
case "$(uname -m)" in
  arm64) SIMULATOR_ARCH="arm64" ;;
  x86_64) SIMULATOR_ARCH="x86_64" ;;
  *)
    echo "unsupported macOS architecture: $(uname -m)" >&2
    exit 1
    ;;
esac

# What the staticlib needs from the system. rustc names them:
#   cargo rustc -p himark-plugins --features metal-shell --release \
#     --target aarch64-apple-ios --lib --crate-type staticlib -- --print native-static-libs
SYSTEM_LIBS="-lc++ -liconv -lobjc -framework CoreFoundation -framework CoreGraphics -framework CoreText -framework CoreVideo -framework Foundation -framework Metal -framework QuartzCore -framework Security -framework UIKit"

build() {
  local target="$1" qualifier="$2"
  local lib_dir="$ROOT/target/$target/release"
  echo "==> cargo build -p himark-plugins --features metal-shell --release --target $target"
  ( cd "$ROOT" && cargo build -p himark-plugins --features metal-shell --release --target "$target" )
  cat >> Generated-iOS.xcconfig <<XC
LIBRARY_SEARCH_PATHS$qualifier = $lib_dir
OTHER_LDFLAGS$qualifier = $lib_dir/libhimark_plugins.a $SYSTEM_LIBS
XC
}

export BINDGEN_EXTRA_CLANG_ARGS_aarch64_apple_ios="--sysroot $(xcrun --sdk iphoneos --show-sdk-path)"
export BINDGEN_EXTRA_CLANG_ARGS_aarch64_apple_ios_sim="--sysroot $(xcrun --sdk iphonesimulator --show-sdk-path) --target=arm64-apple-ios-simulator"
# libtailscale's Go core: the cc-crate CC string carries -Wall -Wextra,
# and Go compiles its own runtime/cgo with -Werror — a sign-compare
# in gcc_darwin_arm64.c fails the cross build without this.
export CGO_CFLAGS="${CGO_CFLAGS:+$CGO_CFLAGS }-Wno-sign-compare"

cat > Generated-iOS.xcconfig <<XC
// Generated by build.sh — do not edit.
HEADER_SEARCH_PATHS = \$(SRCROOT)
ARCHS[sdk=iphoneos*] = arm64
ARCHS[sdk=iphonesimulator*] = $SIMULATOR_ARCH
XC
build aarch64-apple-ios "[sdk=iphoneos*]"
build aarch64-apple-ios-sim "[sdk=iphonesimulator*]"

# The FFI headers the bridging header includes — keep them the build's.
cp "$ROOT/frontend/himark-ffi/include/himark.h" ./himark.h
cp "$ROOT/frontend/workbench-shell/include/himark-shell.h" ./himark-shell.h
cp "$ROOT/frontend/himark-plugins/include/himark-host.h" ./himark-host.h
cp "$ROOT/frontend/hitailnet/include/himark-tailnet.h" ./himark-tailnet.h
cp "$ROOT/frontend/hiahp/include/himark-ahp.h" ./himark-ahp.h

command -v xcodegen >/dev/null || { echo "install XcodeGen: brew install xcodegen"; exit 1; }
xcodegen generate
echo "generated himark.xcodeproj (target: himark-iOS); pick the himark-iOS scheme in Xcode to run on a device or simulator."
