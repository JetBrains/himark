set -euo pipefail
cd "$(dirname "$0")"
ROOT="$(cd ../.. && pwd)"
SKIA_BINDINGS_DIR="$(ls -d "$ROOT"/vendor/skia-bindings-* | sort -V | tail -n 1)"
# The vendored crate ships the pinned Skia source tree — the Metal
# bridge headers come straight from it, version-matched by construction.
SKIA_HEADERS_DIR="$SKIA_BINDINGS_DIR/skia"

# The simulator slice runs on the host's architecture.
case "$(uname -m)" in
  arm64) SIMULATOR_ARCH="arm64" ;;
  x86_64) SIMULATOR_ARCH="x86_64" ;;
  *)
    echo "unsupported macOS architecture: $(uname -m)" >&2
    exit 1
    ;;
esac

ensure_skia_headers() {
  if [[ -f "$SKIA_HEADERS_DIR/include/core/SkCanvas.h" \
    && -f "$SKIA_HEADERS_DIR/modules/skcms/skcms.h" ]]; then
    return
  fi

  echo "the vendored Skia tree at $SKIA_HEADERS_DIR is missing its headers" >&2
  exit 1
}

resolve() {
  local target_flag="$1" lib_dir="$2" out="$3" qualifier="${4:-}" append="${5:-}" xcode_arch="${6:-}"
  echo "==> cargo build -p himark-plugins --features skia-shell,metal-shell --release $target_flag"
  ( cd "$ROOT" && cargo build -p himark-plugins --features skia-shell,metal-shell --release $target_flag >/dev/null )

  local SKIA EXTRA
  {
    read -r SKIA
    read -r EXTRA
  } < <( cd "$ROOT" && cargo build -p himark-plugins --features skia-shell,metal-shell --release $target_flag \
           --message-format=json 2>/dev/null | python3 -c "
import sys, json
out=None; extra=[]
for line in sys.stdin:
    try: m=json.loads(line)
    except Exception: continue
    if m.get('reason')=='build-script-executed' and 'skia-bindings' in m.get('package_id',''):
        out=m['out_dir']
        for l in m.get('linked_libs', []):
            if l.startswith('framework='): extra.append('-framework '+l.split('=',1)[1])
            elif l=='c++': extra.append('-lc++')
        break
assert out, 'no skia out_dir'
print(out+'/skia')
print(' '.join(extra))
")

  if [ -z "$append" ]; then
    cat > "$out" <<XC
// Generated by build.sh — do not edit. Links this build's exact skia.
HEADER_SEARCH_PATHS = \$(SRCROOT) \$(SRCROOT)/Sources/Shared/SkiaMetalBridge/include $SKIA_HEADERS_DIR
XC
    if [ -n "$xcode_arch" ]; then
      echo "ARCHS = $xcode_arch" >> "$out"
    fi
  fi
  cat >> "$out" <<XC
LIBRARY_SEARCH_PATHS$qualifier = $lib_dir $SKIA
OTHER_LDFLAGS$qualifier = $lib_dir/libhimark_plugins.a -lskia -lskia-bindings $EXTRA
XC
  echo "    wrote $out$qualifier (skia: $SKIA)"
}

cp "$ROOT/frontend/himark-ffi/include/himark.h" ./himark.h
cp "$ROOT/frontend/workbench-shell/include/himark-shell.h" ./himark-shell.h
cp "$ROOT/frontend/himark-plugins/include/himark-host.h" ./himark-host.h
cp "$ROOT/frontend/hitailnet/include/himark-tailnet.h" ./himark-tailnet.h
ensure_skia_headers

export BINDGEN_EXTRA_CLANG_ARGS_aarch64_apple_ios="--sysroot $(xcrun --sdk iphoneos --show-sdk-path)"
export BINDGEN_EXTRA_CLANG_ARGS_aarch64_apple_ios_sim="--sysroot $(xcrun --sdk iphonesimulator --show-sdk-path) --target=arm64-apple-ios-simulator"
# libtailscale's Go core: the cc-crate CC string carries -Wall -Wextra,
# and Go compiles its own runtime/cgo with -Werror — a sign-compare
# in gcc_darwin_arm64.c fails the cross build without this.
export CGO_CFLAGS="${CGO_CFLAGS:+$CGO_CFLAGS }-Wno-sign-compare"

resolve "--target aarch64-apple-ios" "$ROOT/target/aarch64-apple-ios/release" Generated-iOS.xcconfig "[sdk=iphoneos*]"
resolve "--target aarch64-apple-ios-sim" "$ROOT/target/aarch64-apple-ios-sim/release" Generated-iOS.xcconfig "[sdk=iphonesimulator*]" append
{
  echo "ARCHS[sdk=iphoneos*] = arm64"
  echo "ARCHS[sdk=iphonesimulator*] = $SIMULATOR_ARCH"
} >> Generated-iOS.xcconfig

command -v xcodegen >/dev/null || { echo "install XcodeGen: brew install xcodegen"; exit 1; }
xcodegen generate
echo "generated himark.xcodeproj (target: himark-iOS)"

echo "iOS built for aarch64-apple-ios; select the himark-iOS scheme in Xcode to run on a device/simulator."
